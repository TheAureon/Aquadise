// Packs the songs listed in assets/music/manifest.js into assets/music/embedded.js (base64), so they also
// play when index.html is opened straight from disk (file://), where browsers block reading files.
// Hosted on a website you don't need this. Run after adding or changing a song:
//   node tools/embed-music.js
// It warns about big files: every song you embed is loaded with the page.
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.join(__dirname, '..');
const ctx = {}; ctx.window = ctx; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'assets/music/manifest.js'), 'utf8'), ctx);
const list = (ctx.AQ.data.musicFiles || []).filter((f) => f && f.file);
const lines = []; let total = 0;
for (const f of list) {
  const p = path.join(ROOT, f.file);
  if (!fs.existsSync(p)) { console.log(`  missing: ${f.file} (check the name in assets/music/manifest.js)`); continue; }
  const b = fs.readFileSync(p); total += b.length;
  if (b.length > 8 * 1024 * 1024) console.log(`  big: ${f.file} is ${(b.length / 1048576).toFixed(1)} MB (see docs/ADDING_MUSIC.md)`);
  lines.push(`  ${JSON.stringify(f.file)}: '${b.toString('base64')}'`);
}
fs.writeFileSync(path.join(ROOT, 'assets/music/embedded.js'),
  '// GENERATED by tools/embed-music.js from the songs in assets/music/manifest.js. Do not edit by hand.\n' +
  "var AQ = (typeof AQ !== 'undefined') ? AQ : {};\nAQ.data = AQ.data || {};\nAQ.data.musicEmbedded = {\n" + lines.join(',\n') + '\n};\n');
console.log(`embedded ${lines.length} of ${list.length} songs (${(total / 1048576).toFixed(1)} MB)`);
